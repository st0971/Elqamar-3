        /* =====================================================
           顯示作品
           ===================================================== */

        function renderGallery(type) {


            const gallery =
                document.getElementById(
                    type + "-gallery"
                );


            const pagination =
                document.getElementById(
                    type + "-pagination"
                );


            gallery.innerHTML = "";

            pagination.innerHTML = "";


            const data =
                portfolio[type];


            const perPage =
                itemsPerPage[type];


            const page =
                currentPage[type];


            const start =
                (page - 1) * perPage;


            const end =
                start + perPage;


            const items =
                data.slice(start, end);



            /* =================================================
               建立作品
               ================================================= */

            items.forEach(function(item) {


                const work =
                    document.createElement("div");


                work.className =
                    "work";



                const imageBox =
                    document.createElement("div");


                imageBox.className =
                    "image-box";



                /* ---------------------------------------------
                   不同頁面的圖片比例
                   --------------------------------------------- */

                if (type === "poster") {

                    imageBox.classList.add(
                        "poster-box"
                    );

                }


                else if (type === "business") {

                    imageBox.classList.add(
                        "business-box"
                    );

                }


                else if (type === "illustration") {

                    imageBox.classList.add(
                        "illustration-box"
                    );

                }


                // else if (type === "other") {

                //     if (item.type === "vertical") {

                //         imageBox.classList.add(
                //             "vertical-box"
                //         );

                //     }

                //     else {

                //         imageBox.classList.add(
                //             "horizontal-box"
                //         );

                //     }

                // }



                /* ---------------------------------------------
                   主要圖片
                   --------------------------------------------- */

                const image =
                    document.createElement("img");


                image.className =
                    "main-image";


                image.src =
                    item.image;


                image.alt =
                    item.title;



                /* ---------------------------------------------
                   海報／名片 AI 標誌
                   --------------------------------------------- */

                if (
                    item.ai === true &&
                    type !== "illustration"
                ) {


                    const ai =
                        document.createElement(
                            "div"
                        );


                    ai.className =
                        "ai-badge";


                    ai.textContent =
                        "AI";


                    imageBox.appendChild(ai);

                }



                /* ---------------------------------------------
                   插畫水印
                   --------------------------------------------- */

                if (
                    type === "illustration"
                ) {

                    const watermark =
                        document.createElement("img");

                    watermark.className =
                        "watermark";

                    watermark.src =
                        "images/LOGO.png";

                    watermark.alt = "";

                    imageBox.appendChild(
                        watermark
                    );

                }
                
                if (
                    type === "other"
                ) {

                    const watermark =
                        document.createElement("img");

                    watermark.className =
                        "watermark";

                    watermark.src =
                        "images/LOGO.png";

                    watermark.alt = "";

                    imageBox.appendChild(
                        watermark
                    );

                }



                imageBox.prepend(image);



                /* ---------------------------------------------
                   作品名稱
                   --------------------------------------------- */

                const description =
                    document.createElement(
                        "div"
                    );


                description.className =
                    "description";


                description.textContent =
                    item.title;



                /* ---------------------------------------------
                   加入作品
                   --------------------------------------------- */

                work.appendChild(
                    imageBox
                );


                work.appendChild(
                    description
                );


                gallery.appendChild(
                    work
                );

            });



            /* =================================================
               建立換頁按鈕
               ================================================= */

            renderPagination(
                type
            );

        }



        /* =====================================================
           建立換頁按鈕
           ===================================================== */

        function renderPagination(type) {


            const pagination =
                document.getElementById(
                    type + "-pagination"
                );


            pagination.innerHTML = "";


            const totalItems =
                portfolio[type].length;


            const perPage =
                itemsPerPage[type];


            const totalPages =
                Math.ceil(
                    totalItems / perPage
                );


            const page =
                currentPage[type];



            /* 如果只有一頁，不顯示換頁按鈕 */

            if (totalPages <= 1) {

                return;

            }



            /* =================================================
               上一頁
               ================================================= */

            const previous =
                document.createElement(
                    "button"
                );


            previous.textContent =
                "‹";


            previous.disabled =
                page === 1;


            previous.onclick =
                function() {

                    if (page > 1) {

                        currentPage[type]--;

                        renderGallery(type);

                        scrollToGallery();

                    }

                };


            pagination.appendChild(
                previous
            );



            /* =================================================
               頁碼
               ================================================= */

            for (
                let i = 1;
                i <= totalPages;
                i++
            ) {


                const pageButton =
                    document.createElement(
                        "button"
                    );


                pageButton.textContent =
                    i;


                if (i === page) {

                    pageButton.classList.add(
                        "active"
                    );

                }


                pageButton.onclick =
                    function() {

                        currentPage[type] =
                            i;

                        renderGallery(type);

                        scrollToGallery();

                    };


                pagination.appendChild(
                    pageButton
                );

            }



            /* =================================================
               下一頁
               ================================================= */

            const next =
                document.createElement(
                    "button"
                );


            next.textContent =
                "›";


            next.disabled =
                page === totalPages;


            next.onclick =
                function() {

                    if (page < totalPages) {

                        currentPage[type]++;

                        renderGallery(type);

                        scrollToGallery();

                    }

                };


            pagination.appendChild(
                next
            );

        }



        /* =====================================================
           換頁後稍微回到作品區
           ===================================================== */

        function scrollToGallery() {

            window.scrollTo({

                top: 0,

                behavior: "smooth"

            });

        }



        /* =====================================================
           導覽列切換
           ===================================================== */

        function showPage(
            pageId,
            button
        ) {


            const pages =
                document.querySelectorAll(
                    ".page"
                );


            const buttons =
                document.querySelectorAll(
                    ".nav-btn"
                );



            /* 隱藏全部頁面 */

            pages.forEach(
                function(page) {

                    page.classList.remove(
                        "active"
                    );

                }
            );



            /* 移除按鈕 active */

            buttons.forEach(
                function(btn) {

                    btn.classList.remove(
                        "active"
                    );

                }
            );



            /* 顯示目前頁面 */

            document
                .getElementById(pageId)
                .classList.add(
                    "active"
                );



            /* 標記目前按鈕 */

            button.classList.add(
                "active"
            );



            /* 回到頂部 */

            window.scrollTo({

                top: 0,

                behavior: "smooth"

            });

        }



